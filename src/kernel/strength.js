/**
 * 隊伍強度。
 *
 * 三個函式住在一起是因為它們永遠一起被改——調權重時三個都要看。
 */
import { COACHES } from '../data/coaches.js';
import { LEAGUES } from '../data/leagues.js';
import { positionPower } from '../engine/attributes.js';
import { trustBonus } from '../engine/mental.js';
import { staminaOf, staminaPower } from '../engine/stamina.js';
import { factor, floorOf } from './modifiers.js';

export function coachBonus(state) {
  return (COACHES.find((c) => c.name === state.coach)?.bonus || 0) * factor(state, 'coachMult');
}

export function matesAverage(state) {
  if (!state.mates || !state.mates.length) return 0;
  const sum = state.mates.reduce((t, m) => t + m.rating, 0);
  // mateMorale 是單季的士氣，trust 是跨季累積的信任（V4 §9.4 把舊的 chem 併進去）——兩者相加
  return sum / state.mates.length + floorOf(state, 'teamLead', 0) + (state.mateMorale || 0) + trustBonus(state);
}

/**
 * 所在聯賽的先發平均。業餘期還沒有 `state.league`，落回網咖盃的 par。
 *
 * ⚠ **回退值只有這一個**（S20c／N13）：`engine/lineup.js` 的 `benchRisk` 原本自己
 * 寫 `?? 66`（主場賽區的 par），這裡回退 43（AMATEUR par）。同一個「聯賽查不到」
 * 的情境兩個答案差 23 點，而 23 點在 `benchRisk` 是「打不到隊伍平均」的懲罰
 * 五十幾個百分點。導出而不是各寫各的。
 */
export function parOf(state) {
  return LEAGUES[state.league ?? 'AMATEUR']?.par ?? LEAGUES.HOME.par;
}

/**
 * 對手的支援值：把 §11.1 階梯表的「對手水準」換算成可以跟 `teamStrength` 相減的
 * 「對手隊伍強度」。
 *
 * S29 逐選手對手模型上線後（§23.4），對手強度分兩條路：**實體化對手**（陣容完整的
 * NPC 隊）強度從五人陣容現算，常數只剩教練／體力殘項（`OPPONENT_SUPPORT_RESIDUAL`，
 * 見下）；**匿名對手**（常規賽與陣容缺口年份的落回）仍走這個常數——
 * 「對手也是一支隊」的錯位校正一點沒變。
 *
 * ⚠ **這不是憑空多出來的加碼，是把兩邊的單位對齊。** §11.1 的對手強度階梯是 `par`
 * 系的數字，而 `par` 的定義是「該聯賽**先發平均教練評價**」——那是**一個選手**的水準。
 * 我們這邊的 `teamStrength` 卻是一支隊的強度（含教練、體力、明星項）。直接相減等於
 * 讓對面用一個選手來打我們一支隊。
 *
 * 舊制看不出這個錯位，因為 0.55／0.35 的權重和只有 0.90，在 par 66 時把隊伍強度壓低
 * 6.6 點，剛好被那份支援抵掉（淨值約 par −1.1）。V4 §11.1 把權重和改成 1.00、教練與
 * 體力變成純加項之後，錯位就直接顯形：實測 160 段生涯的國際賽冠軍當量從 39 段暴增到
 * 84 段，`五個等第都出現得到` 也因為沒人再打得爛而翻紅。
 *
 * 值怎麼來的（兩份都對得上，所以取 6.5）：
 *
 * 1. **推導**：對手也是一支隊，所以它有 §11.1 驗算例寫的「教練/體力 3.5」，也有
 *    **它自己的明星選手**——階梯上的隊伍是賽區冠軍等級，carry 大約高出該聯賽 par
 *    15～20 點。
 * 2. **實測**：掃值跑 640 段生涯，看世界冠軍人均與「有國際冠軍的生涯」段數有沒有
 *    回到上一站的校準。
 *
 * ⚠ **S12 把它從 6.5 調到 9.0，理由是 §9.2 也發生在對手身上。**
 *
 * S11 推導 6.5 時，`positionPower` 還沒有心理乘法項，所以階梯上那個 carry 的戰力
 * 就等於它的名目評價。V4 §9.2 上線之後不是這樣了：**每一支隊的 carry 都乘上
 * 0.85–1.15 的發揮倍率**，而階梯上的隊伍是賽區冠軍等級，它的 carry 心理不會差。
 * 實測 640 段生涯，有國際冠軍那一群的心理穩定修正平均是 **1.04**，所以同一個 carry：
 *
 * - 明星項：par+17.5 = 83.5 → ×1.04 = 86.8，超出 par 從 17.5 變 20.8，
 *   查 §11.1 的公式 `0.06 × 20.8^1.35` ＝ **3.56**（S11 當時算的是 3.0）。
 * - 它在自家隊伍強度裡的份額：P 高了 3.3 點，×0.60 ＝ **+2.0**。
 *
 * 3.5 ＋ 3.56 ＋ 2.0 ＝ **9.06**，取 9.0。實測對得上：640 段生涯的世界冠軍人均
 * 0.248 → **0.128**（S11 是 0.113）、有國際冠軍的生涯 150 → **123 段**（S11 是 122）、
 * 平均薪資 +2.5%、平均巔峰 +0.1%。**不改的話世界冠軍人均會是 S11 的 2.2 倍**——
 * 那不是 §9.2 想要的效果，是拿只有我方享有的加成去打沒有加成的對手。
 *
 * ⚠ 對照組（都跑過 640 段）：把國際賽的抗壓獎勵減半完全無效（0.248 → 0.253），
 * 所以**這不是「贏了長抗壓、抗壓又幫你贏」的回饋迴圈**，是整體戰力上移。把 §9.2
 * 的乘法項釘成 1 則直接回到 0.125——單一根因確認。
 */
export const OPPONENT_SUPPORT = 9.0;

/**
 * 實體化對手的教練／體力殘項（§23.4，S29 落地，**S30 定案 16.5**）。
 *
 * 上面那個 9.0 的推導拆成三項：對手教練／體力 **3.5** ＋ 隱性對手明星 **3.56** ＋
 * carry 份額 **2.0**。實體化之後後兩項由陣容現算——明星項走 `starTerm` 對對手主場
 * 聯賽 par 顯式計算，carry 份額就是聚合式裡 `P_carry × 0.60` 那一項。
 *
 * ⚠ **S29 留的起始值 3.5 只補了第一項，基線大偏移**——S30 重推（判準 → 量測 → 結論）：
 *
 * 1. **判準**：§23.4 明文「強度數學的校準錨點不動」——實體化對手的平均強度要回到
 *    舊匿名路（階梯目標 + 9.0）的水準；對齊的數字是 S28 基線（160 段實測）：國際賽
 *    局勝率 **53.1%**、世界冠軍人均 **0.081**、頂端落差 **0.172**、傳說持有 **20.6%**。
 * 2. **量測**：S29 已量出實體化對手比舊匿名平均弱 **13.14 點**（carry 構成 −6.19、
 *    殘項換算 −5.5、明星項顯式化 −3.41、選隊漂移 −1.61）。S30 以此推終值
 *    3.5 + 13.14 ≈ 16.6，並掃 13–18 逐值對照：**16.5 時國際賽局勝率 52.7%**
 *    （錨 53.1%，掃值裡最貼）、頂端落差 0.175、平均巔峰 74.20（錨 74.16）、
 *    傳說持有 18.1%（15–25% 帶內）；13／14 偏軟（勝率 56–57%、傳說持有 22–25%），
 *    18 以上冠軍計數與勝率不再單調收斂（稀有事件在 160 段的確定性混沌）。
 * 3. **結論**：**取 16.5**——實體化路在期望上回到舊匿名路的強度，兩條路同一個難度。
 *    ⚠ 冠軍人均不逐顆對齊（世界冠軍 0.031＝5 座、MSI 0.181＝29 座 vs 錨 13／21 座）：
 *    稀有事件樣本太小，且選隊漂移與明星項的結構差不是單一常數能逐顆補回的；
 *    穩定分布（勝率／巔峰／落差／持有率）全部落錨，即視為校準收斂。
 *
 * S12 的乘法鏈警告繼續適用：動 `positionPower` 乘法項的站要回來重推它。
 * 量測工具：`tools/calibrate-160.mjs`（S36 重校同一套）。
 */
export const OPPONENT_SUPPORT_RESIDUAL = 16.5;

/**
 * 把階梯表的對手水準換成可以跟 `teamStrength` 相減的隊伍強度。
 * 所有「拿階梯值當對手」的地方都要走這裡，否則就是拿一個選手比一支隊。
 */
export function opponentStrength(ladderRating) {
  return ladderRating + OPPONENT_SUPPORT;
}

/**
 * 明星效應（V4 §11.1）：`min(6.0, 0.06 × max(0, P − par)^1.35)`。
 *
 * 超線性的用意是「一個人拉抬一支隊」要看得出來，但拉不動整隊。三個參數都是 §11.1
 * 推導過的：指數 1.35 讓 P−par 每翻一倍、明星項變 2.55 倍；係數 0.06 由上界回推，
 * 讓 6.0 點落在 P−par ≈ 30（幾乎只有滿等選手在主場賽區碰得到）；上界 6.0 點 ＝
 * 勝率 +10.6 個百分點（×1.76）。
 *
 * **不另外設起算門檻**：指數 >1 本身就讓中段幾乎沒有份量（P−par = 5 只換到 0.53 點），
 * 再切一刀只會製造不連續。有效起點自然落在 P−par ≈ 8。
 *
 * ⚠ 基準是**聯賽 par 而不是隊友均值**，這點試過反面：隊友是 `par ± 7` 生成的，均值
 * 就是 par，但明星項是凸函數，所以改吃隊友均值會讓「抽到爛隊友」的人多領一份，
 * 期望值反而上升（實測世界冠軍 49 → 54 座、頂到勝率上限的生涯 18 → 20 段，兩項都
 * 更糟）。§11.1 寫 par 是對的。
 */
export function starEffect(state, power) {
  return starTerm(power, parOf(state));
}

/**
 * 明星項的純形式（§11.1）：`min(6.0, 0.06 × max(0, P − par)^1.35)`。
 *
 * S29 把對手側明星項顯式化（§23.4）：實體化對手的主 carry 用同一條公式對
 * **對手主場聯賽 par** 計算——明星項一邊一個，不另設第三個機制。玩家側照舊走
 * `starEffect`（讀所在聯賽 par），所以拆成這個吃 par 的純函式，兩邊共用。
 */
export function starTerm(power, par) {
  const over = Math.max(0, power - par);
  return Math.min(6.0, 0.06 * (over ** 1.35));
}

/**
 * 隊伍整體強度。用於勝率計算。
 *
 * V4 §11.1：`P × 0.60 + 隊友均值 × 0.40 + 教練加成 + 體力修正 + 明星項`。
 *
 * ⚠ **權重從 0.55／0.35 改成 0.60／0.40，這不只是加重玩家的份量**：舊的兩個權重
 * 加起來只有 0.90，等於整隊的強度被系統性地壓低一成（在 par 66 時是 −6.6 點），
 * 再由教練與體力那 ~5 點補回來——淨值大約 par −1.3。新版權重和是 1.00，教練與體力
 * 變成純粹的加項，所以同一支隊的強度會整體上移。這是 §11.1 算過的：它的驗算例
 * （P=100、隊友 59）明寫「教練/體力 3.5」疊在 0.60/0.40 之上。
 *
 * 上移的後果是刻意的——常規賽對手基準就是 `par`（§11.1「練得糊也打得過，這是刻意
 * 的」），而國際賽有 72／74 的絕對地板。**篩選發生在頂端，不發生在聯賽**。
 *
 * 玩家仍然只是五分之一：0.60 對 0.40，加上明星項封頂 6.0 點，滿等選手配上生成
 * 區間下界的隊友、對上世界賽淘汰賽的對手仍然只有七成多的單局勝率，頂不到 92% 的
 * 上限。個人數據再漂亮，隊伍進不了季後賽就是進不了。
 */
export function teamStrength(state) {
  const power = positionPower(state);
  return power * 0.60
    + matesAverage(state) * 0.40
    + coachBonus(state)
    // 體力修正（§11.1）。S13 之後讀的是真的會消耗的 `state.stamina`，係數與量級的
    // 校準理由寫在 `engine/stamina.js` 的 `staminaPower`
    + staminaPower(staminaOf(state))
    + starEffect(state, power);
}
