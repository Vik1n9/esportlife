/**
 * 聲量層（V4 §9.4）。純資料，無邏輯。
 *
 * `fame` 從心理六維裡拆出來獨立成一層，因為它跟那六個**不是同一種東西**：
 *
 * |          | 隱藏心理六維        | 聲量 fame          |
 * | -------- | ------------------ | ------------------ |
 * | 玩家可見 | 否（§9.1）          | **是**             |
 * | 分級標籤 | 沒有                | **有**（就在下面）  |
 * | 誰在讀   | 技能發揮、失誤率     | 續約加薪、代言、傳聞熱度、外援名額 |
 *
 * v3 之前把兩者混在同一張表，於是面板上會同時出現「全民認識」與「大場面型」——
 * 前者是聲量、玩家本來就該知道，後者等於直接洩漏抗壓值。§9.4 要守的就是這條線。
 *
 * 聲量**不分好壞**。舊版另有一條 `rep`（風評）可以是負的，V4 §9.4 把它整條拿掉了：
 * 戰隊切不切割你改看教練評價與特質副作用，不再有一個「圈內怎麼說你」的獨立數值。
 * 留下來的只有「多少人認得你」這一個量。
 */

export const FAME_KEY = 'fame';
export const FAME_NAME = '知名度';
export const FAME_RANGE = [0, 100];

/** 新人的起始區間：沒沒無聞是常態 */
export const FAME_START = [0, 5];

/** 面板上的分級敘述。這是**唯一**還有分級標籤的心理／聲量數值 */
export const FAME_TIERS = [
  [80, '全民認識'], [62, '圈內名人'], [40, '有點知名度'], [15, '小有耳聞'], [-999, '沒沒無聞'],
];

export function fameTier(value) {
  const row = FAME_TIERS.find(([at]) => value >= at);
  return row ? row[1] : '';
}
