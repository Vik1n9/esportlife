/**
 * 心理與性格維度。純資料，無邏輯。
 *
 * 這一條軸刻意跟 `ability`（操作／反應／對線…）完全分開：
 * 能力值靠訓練骰養，心理值只能靠「扮演」——賽前放話、媒體採訪、休息室對話、
 * 教練談話。玩家不能把訓練點投進大心臟，只能一次一次選擇把人演成那樣。
 *
 * 五個維度：
 * - `nerve` 大心臟：BO 決勝局與國際賽的抗壓，決定「下剋上」劇本成不成立。
 * - `chem`  隊友默契：直接進隊伍強度；跌到谷底會被迫轉隊（Aming 那種）。
 * - `ego`   自我：放話／爭議發言的放大器。高自我讓話題效果加倍，但磨損默契。
 * - `fame`  知名度：不分好壞的聲量。續約時戰隊「不得不加薪留人」看的是這個。
 * - `rep`   風評：唯一可以是負的維度。低到見底戰隊會切割，甚至直接開除。
 *
 * `fame` 與 `rep` 分開是刻意的——Bin 那種誇張言行同時收穫人氣與負評，
 * 用單一「人氣」數值表達不出來。
 */

export const MENTAL_KEYS = ['nerve', 'chem', 'ego', 'fame', 'rep'];

export const MENTAL_NAMES = {
  nerve: '大心臟', chem: '隊友默契', ego: '自我', fame: '知名度', rep: '風評',
};

/** [min, max]。只有 rep 可以是負的。 */
export const MENTAL_RANGE = {
  nerve: [0, 100], chem: [0, 100], ego: [0, 100], fame: [0, 100], rep: [-100, 100],
};

/** 新人的起始區間（由亂數在區間內取值） */
export const MENTAL_START = {
  nerve: [32, 48], chem: [45, 58], ego: [30, 55], fame: [0, 5], rep: [0, 10],
};

