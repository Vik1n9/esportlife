/**
 * 競技心理六維（V4 §9）。純資料，無邏輯。
 *
 * ⚠ 這一組跟 v3 的 `nerve／chem／ego／fame／rep` **不是同一條軸**。舊的那五個是
 * 社交與聲量（你在鏡頭前是什麼樣的人、圈內怎麼說你），新的六個是競技心理
 * （你在場上打不打得出你的實力）。V4 §9.4 把兩者的界線劃清楚：
 *
 *   `nerve` → `comp`（同一件事，換成競技語彙）
 *   `chem`  → 併入 `trust`（默契是「你相不相信隊友會跟上」的結果，不是獨立的一維）
 *   `ego`   → 不留維度，放大器角色改由特質副作用承擔（嘴砲王／獨狼／圈內毒瘤）
 *   `rep`   → 不留維度，切割判定改讀教練評價 ＋ 特質副作用
 *   `fame`  → **不在這個檔**。它可見、有標籤，搬去 `data/reputation.js` 獨立成一層
 *
 * 六個維度：
 * - `comp`  抗壓：大賽與關鍵局的發揮，受迫性失誤的主要守門員。
 * - `conf`  自信：敢不敢做那一個極限操作。**雙向**——過高會貪，是非受迫性失誤的來源。
 * - `drive` 動機：訓練收益、倦怠、退役意圖。場上發揮的份量刻意最輕（§9.2）。
 * - `disc`  紀律：重複的細節不出錯，非受迫性失誤的主導維度。
 * - `trust` 信任：隊內協作、默契判定、轉會適應。
 * - `resl`  韌性：連敗恢復、傷病回歸，受迫性失誤的第二道守門員。
 *
 * **這六個值永遠不對玩家顯示，連粗略標籤都不給**（§9.1）。舊版面板上的
 * 「大場面型」「一上大場面就抖」等於直接把抗壓值攤開，玩家會開始最佳化它——
 * 那條線一破，「因隱藏、果可見」的推測循環就沒了。玩家只能從事件文本、結算箭頭
 * 與可見數據（陣亡、關鍵局表現）反推。分級標籤留給聲量（`data/reputation.js`）。
 */

export const MENTAL_KEYS = ['comp', 'conf', 'drive', 'disc', 'trust', 'resl'];

/** 只用在事件結算的箭頭說明（「抗壓 ↑↑」），不用在任何常駐面板 */
export const MENTAL_NAMES = {
  comp: '抗壓', conf: '自信', drive: '動機', disc: '紀律', trust: '信任', resl: '韌性',
};

/** [min, max]。六維全部 0–100——舊版 `rep` 那種負值區間跟著維度一起拿掉了 */
export const MENTAL_RANGE = Object.fromEntries(MENTAL_KEYS.map((k) => [k, [0, 100]]));

/**
 * 起始值（V4 §9.1）：全部從 50 出發，由出生種子微調 ±10。
 *
 * 舊版每一維各有自己的起始區間（大心臟 32–48、默契 45–58…），那是因為它們量的是
 * 不同的東西。六維是同一條刻度上的六個面向，所以起點一致，差異全部來自天賦骰——
 * 這樣「50 是基準」在 §9.2 的發揮公式與 §10.2 的心理修正才都成立（兩邊在 50 都恰好
 * 是中性值），任何偏離都是玩家自己選出來的。
 */
export const MENTAL_BASE = 50;
export const MENTAL_JITTER = 10;
