/**
 * 潛力衰減係數（V4 §5.3 §7.1）——取代舊的成長成本階梯。
 *
 * 舊制是「玩家有訓練點、屬性越高每點越貴」（凸的成本階梯）；設施制是「訓練活動給
 * 固定的基礎成長值、越接近潛力天花板長得越少」。這是同一件事的兩面，但**換刻度
 * 不換模型會做出四不像**，所以這裡寫成乘法係數而不是成本：
 *
 *     潛力衰減係數 = 級距係數(現值) × 天花板係數(潛力 − 現值)
 *
 * 級距係數就是舊成本的倒數（1/1、1/2、1/4、1/7），門檻是舊值 ×1.25（46/54/62 →
 * 58/68/78）。所以「絕對級距」這一半的行為與舊制等價，換掉的是另一半：舊制在潛力
 * 天花板以下完全不看距離（潛力 60 與 90 的成長一模一樣），新制連續遞減。
 */
export const GROWTH_TIER_COEF = [
  { at: 78, coef: 0.14 },   // 舊成本 7 點
  { at: 68, coef: 0.25 },   // 舊成本 4 點
  { at: 58, coef: 0.50 },   // 舊成本 2 點
  { at: 0, coef: 1.00 },    // 舊成本 1 點
];

/**
 * 天花板係數 = `CEILING_FLOOR + (1 − CEILING_FLOOR) × min(max(潛力 − 現值, 0), 12) / 12`
 *
 * - **0.34 的由來**：舊制超過潛力上限之後成本 ×3（`OVER_POTENTIAL_MULTIPLIER`），
 *   倒數就是 1/3。所以潛力仍然是**軟**天花板——練得夠久還是過得去，只是很慢。
 * - **12 的由來**：0–100 刻度下單一屬性一年約漲 8–12 點，所以「最後一年的距離」才
 *   開始遞減。§7.1 實測把錐度起點從 8 掃到 20，打法差距只從 0.0155 動到 0.0172×上限。
 *
 * ⚠ 不要把 `CEILING_FLOOR` 改成 0（硬天花板）。§7.1 實測硬天花板要 1.85 倍的訓練
 * 預算才能把平均巔峰推回 0.755，而且低端尾巴被拉開——潛力會從「你要練多久」變成
 * 「你這局結束了」，那不是 §5.3 想要的曲線。
 */
export const CEILING_FLOOR = 0.34;
export const CEILING_TAPER = 12;

